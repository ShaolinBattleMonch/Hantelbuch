create role service_role nologin;
create role anon nologin; create role authenticated nologin;
create schema extensions; create schema auth; create schema storage; create schema cron;
create table auth.users (id uuid primary key, email text);
create function auth.uid() returns uuid language sql stable as $$ select nullif(current_setting('request.jwt.claim.sub', true), '')::uuid $$;
grant usage on schema auth to anon, authenticated; grant execute on function auth.uid() to anon, authenticated;
create table storage.buckets (id text primary key, name text, public bool, file_size_limit bigint, allowed_mime_types text[]);
create table storage.objects (id serial primary key, bucket_id text, name text);
alter table storage.objects enable row level security;
create function storage.foldername(name text) returns text[] language sql immutable as $$ select (string_to_array(name, '/'))[1:array_length(string_to_array(name, '/'),1)-1] $$;
grant usage on schema storage to authenticated; grant select, insert on storage.objects to authenticated; grant usage, select on storage.objects_id_seq to authenticated;
grant execute on function storage.foldername(text) to authenticated;
create publication supabase_realtime;
create function cron.schedule(a text, b text, c text) returns bigint language sql as $$ select 1::bigint $$;
grant usage on schema public to anon, authenticated;
